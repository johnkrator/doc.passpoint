export function isValidSourcePath(path: string): boolean {
  const normalised =
    ("/" + path.replace(/^\/+/, "")).split("?")[0].split("#")[0].replace(/\/$/, "") || "/";
  return VALID_ROUTE_PATHS.has(normalised);
}
